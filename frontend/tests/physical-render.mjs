import { chromium,expect } from '@playwright/test';
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1300,height:1000}});
page.on('pageerror',error=>console.error(error));
try{
 await page.goto('http://127.0.0.1:5175/tests/physical-render-harness.html');
 await expect(page.locator('[data-static-artwork]').first()).toBeVisible();
 const counts=await page.evaluate(()=>({...window.artworkRenderCounts}));
 expect(counts.board).toBe(1);expect(counts.module).toBeGreaterThan(0);
 const led=page.locator('[data-live-overlay]>circle').first();
 const off=await led.getAttribute('fill');
 await page.getByRole('button',{name:'Advance fixture telemetry'}).click();
 await expect(led).not.toHaveAttribute('fill',off);
 expect(await page.evaluate(()=>window.artworkRenderCounts)).toEqual(counts);
 await page.getByRole('button',{name:'Advance fixture telemetry'}).click();
 await expect(page.locator('.evidence-label')).toHaveText('Last known state');
 await expect(led).toHaveAttribute('opacity','0.45');
 expect(await page.evaluate(()=>window.artworkRenderCounts)).toEqual(counts);
 await page.getByRole('combobox',{name:'Artwork profile',exact:true}).click();
 await page.getByRole('option',{name:'Arduino UNO R3',exact:true}).click();
 expect((await page.evaluate(()=>window.artworkRenderCounts)).board).toBe(counts.board+1);
 await page.getByRole('button',{name:'Pending command fixture'}).click();
 await expect(page.getByRole('button',{name:'Turn on',exact:true})).toBeDisabled();
 await expect(page.getByText('Waiting for matching device telemetry.',{exact:false})).toBeVisible();
 await expect(led).toHaveAttribute('opacity','0.45');
 await page.getByRole('button',{name:'Empty session fixture'}).click();
 await expect(page.locator('.evidence-label')).toHaveText('Configured only');
 await expect(page.getByText('No readings in this session',{exact:true})).toBeVisible();
 await page.getByRole('combobox',{name:'Physical device',exact:true}).click();
 await page.getByRole('option',{name:'fixture-b',exact:true}).click();
 await expect(page.locator('.instrument-device strong')).toHaveText('fixture-b');
 await expect(page.getByRole('combobox',{name:'Artwork profile',exact:true})).toHaveAttribute('data-value','default');
 await page.getByRole('combobox',{name:'Physical device',exact:true}).click();
 await page.getByRole('option',{name:'Unassigned components',exact:true}).click();
 await expect(page.locator('.instrument-selection h4')).toHaveText('Unassigned fixture');
 await page.getByRole('checkbox',{name:'Show inferred associations'}).check();
 expect(await page.locator('[data-provenance=inferred]').count()).toBe(0);
 await page.evaluate(()=>{const key=Object.keys(localStorage).find(k=>k.startsWith('agentwin-artwork:'));localStorage.setItem(key,JSON.stringify('future-unknown'));});
 await page.reload();
 await expect(page.getByText(/Unknown profile.*generic artwork/)).toBeVisible();
 await expect(page.locator('[data-static-artwork]').first()).toHaveAttribute('data-static-artwork','generic');
 await page.evaluate(()=>{const key=Object.keys(localStorage).find(k=>k.startsWith('agentwin-artwork:'));localStorage.setItem(key,'{broken');});
 await page.reload();
 await expect(page.getByRole('combobox',{name:'Artwork profile',exact:true})).toHaveAttribute('data-value','default');
 console.log('Actual artwork render counters: live and stale updates leave memoized SVG subtrees untouched; profile change renders the board.');
 console.log('Device switching, unassigned components, pending commands, empty session isolation, unknown and malformed preferences passed.');
}finally{await browser.close();}
